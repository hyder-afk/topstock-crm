-- A lead's tasks the caller can see: open ones by due time (all-day tasks at the start of their day in the caller's
-- zone, undated last), then, when asked, done ones newest first. Dismissed tasks are not listed.
create function public.list_lead_tasks(p_company uuid, p_include_done boolean default false, p_limit integer default 20)
returns table (
  id uuid,
  title text,
  kind text,
  due_date date,
  due_at timestamptz,
  done_at timestamptz,
  assignee_id uuid,
  assignee_first_name text,
  assignee_last_name text,
  contact_id uuid,
  contact_name text,
  created_by uuid,
  source_activity_id uuid,
  created_at timestamptz
)
language plpgsql stable set search_path = '' as $$
#variable_conflict use_column
declare
  v_tz text;
begin
  if (select auth.uid()) is null or not (select private.has_aal2()) then
    raise exception 'two-factor sign-in required' using errcode = '42501';
  end if;
  if p_limit is null or p_limit not between 1 and 100 then
    raise exception 'between 1 and 100 tasks' using errcode = '22023', hint = 'bounds';
  end if;
  v_tz := private.caller_zone();
  return query
    select t.id, t.title, t.kind, t.due_date, t.due_at, t.done_at, t.assignee_id, p.first_name, p.last_name,
           t.contact_id, nullif(btrim(k.first_name || ' ' || k.last_name), ''), t.created_by, t.source_activity_id,
           t.created_at
      from public.tasks t
      left join public.profiles p on p.id = t.assignee_id
      left join public.contacts k on k.id = t.contact_id
     where t.company_id = p_company and t.cancelled_at is null and (t.done_at is null or coalesce(p_include_done, false))
     order by t.done_at is not null, coalesce(t.due_at, t.due_date::timestamp at time zone v_tz) nulls last,
              t.done_at desc, t.created_at, t.id
     limit p_limit;
end;
$$;

-- The status menu's "Until when?" for Cool off (design 3.2): bulk_update_leads gains p_next_action_at, allowed only
-- with p_status = 'cool_off' and bounded by lead_guard. Changes an approved Day 3a signature only to fix a real bug
-- (lead_guard rule 5 already gives every other path a 90-day return).
drop function public.bulk_update_leads(uuid[], text, boolean, uuid);
create function public.bulk_update_leads(
  p_ids uuid[],
  p_status text default null,
  p_set_owner boolean default false,
  p_owner uuid default null,
  p_next_action_at timestamptz default null
) returns integer
language plpgsql volatile set search_path = '' as $$
declare
  n integer;
begin
  if p_ids is null or cardinality(p_ids) = 0 or cardinality(p_ids) > 500 then
    raise exception 'between 1 and 500 leads at a time' using errcode = '22023';
  end if;
  if p_status is null and not coalesce(p_set_owner, false) then
    raise exception 'nothing to change' using errcode = '22023';
  end if;
  if p_next_action_at is not null and p_status is distinct from 'cool_off' then
    raise exception 'a return date goes with Cool off only' using errcode = '22023', hint = 'until_cool_off_only';
  end if;
  update public.companies
     set lead_status = coalesce(p_status, lead_status),
         owner_id = case when coalesce(p_set_owner, false) then p_owner else owner_id end,
         next_action_at = coalesce(p_next_action_at, next_action_at)
   where id = any (p_ids);
  get diagnostics n = row_count;
  return n;
end;
$$;

-- ===========================================================================
-- Function privileges: trigger functions are never callable; the helpers the RPCs use are callable by signed-in
-- people (private has no API endpoint); every RPC is revoked from public and anon and granted to authenticated.
-- ===========================================================================
revoke all on function private.lead_guard(), private.contact_guard() from public, anon, authenticated;
revoke all on function private.next_working_day(timestamptz, integer, text), private.call_attempts(uuid),
  private.caller_zone(), private.logged_activity(uuid, boolean) from public, anon;
grant execute on function private.next_working_day(timestamptz, integer, text), private.call_attempts(uuid),
  private.caller_zone(), private.logged_activity(uuid, boolean) to authenticated;

do $$
declare
  f text;
begin
  foreach f in array array[
    'public.get_lead(uuid)',
    'public.list_lead_activities(uuid, text[], timestamptz, uuid, integer)',
    'public.get_activity(uuid)',
    'public.log_activity(uuid, text, text, text, uuid, text, date, timestamptz, text, uuid, boolean)',
    'public.undo_activity(uuid)',
