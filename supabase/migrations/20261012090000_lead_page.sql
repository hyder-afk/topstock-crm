    'phone_wrong_at', c.phone_wrong_at,
    'attempts', private.call_attempts(c.id),
    'open_task_count', (select count(*) from public.tasks t
                         where t.company_id = c.id and t.done_at is null and t.cancelled_at is null),
    'next_task', (select jsonb_build_object('id', t.id, 'title', t.title, 'kind', t.kind, 'due_date', t.due_date,
                                            'due_at', t.due_at, 'assignee_id', t.assignee_id)
                    from public.tasks t
                   where t.company_id = c.id and t.done_at is null and t.cancelled_at is null
                   order by coalesce(t.due_at, t.due_date::timestamp at time zone z.tz) nulls last, t.created_at, t.id
                   limit 1),
    -- Admins only: import_batches is readable by admins alone.
    'import', (select jsonb_build_object('id', b.id, 'filename', b.filename, 'created_at', b.created_at)
                 from public.import_batches b where b.id = c.import_batch_id),
    'contacts', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', k.id, 'first_name', k.first_name, 'last_name', k.last_name, 'title', k.title,
               'email', k.email, 'phone', k.phone, 'phone_wrong_at', k.phone_wrong_at) order by k.created_at, k.id)
      from public.contacts k where k.company_id = c.id), '[]'::jsonb)
  )
  from public.companies c
  left join public.profiles o on o.id = c.owner_id
  cross join lateral (select (select private.is_manager_or_admin()) or c.owner_id = (select auth.uid()) as can_edit) e
  cross join lateral (select private.caller_zone() as tz offset 0) z  -- offset 0: worked out once, not once per task
  where c.id = p_id
$$;

-- One page of a lead's timeline, newest first: keyset on (created_at, id), two static queries (with and without a
-- cursor) so the cursor is always an index condition. Text is cut at 2,000 characters (get_activity has the rest).
create function public.list_lead_activities(
  p_company uuid,
  p_types text[] default null,
  p_before_at timestamptz default null,
  p_before_id uuid default null,
  p_limit integer default 30
) returns table (
  id uuid,
  type text,
  outcome text,
  body text,
  truncated boolean,
  contact_id uuid,
  contact_name text,
  user_id uuid,
  user_first_name text,
  user_last_name text,
  created_at timestamptz,
  edited_at timestamptz,
  is_mine boolean,
  undo_until timestamptz,
  task_title text,
  task_due_date date,
  task_due_at timestamptz,
  task_done_at timestamptz
)
language plpgsql stable set search_path = '' as $$
#variable_conflict use_column
declare
  caller constant uuid := (select auth.uid());
begin
  if caller is null or not (select private.has_aal2()) then
    raise exception 'two-factor sign-in required' using errcode = '42501';
  end if;
  if p_limit is null or p_limit not between 1 and 100 then
    raise exception 'between 1 and 100 entries a page' using errcode = '22023', hint = 'bounds';
  end if;
  if (p_before_at is null) <> (p_before_id is null) then
    raise exception 'a cursor needs both its time and its id' using errcode = '22023', hint = 'bad_cursor';
  end if;
  if p_types is not null and (cardinality(p_types) not between 1 and 5
                              or not p_types <@ array['call', 'email', 'whatsapp', 'meeting', 'note']) then
    raise exception 'unknown kind of entry' using errcode = '22023', hint = 'bad_types';
  end if;
  if p_before_at is null then
    return query
      select a.id, a.type, a.outcome, left(a.body, 2000), char_length(a.body) > 2000, a.contact_id,
             nullif(btrim(k.first_name || ' ' || k.last_name), ''), a.user_id, p.first_name, p.last_name,
             a.created_at, a.edited_at, a.user_id = caller,
             case when a.user_id = caller and a.created_at > now() - interval '120 seconds'
                       and exists (select 1 from private.activity_undo u where u.activity_id = a.id)
                  then a.created_at + interval '120 seconds' end,
             t.title, t.due_date, t.due_at, t.done_at
        from (select x.* from public.activities x
               where x.company_id = p_company and (p_types is null or x.type = any (p_types))
               order by x.created_at desc, x.id desc
               limit p_limit) a
        left join public.contacts k on k.id = a.contact_id
        left join public.profiles p on p.id = a.user_id
        left join lateral (select s.title, s.due_date, s.due_at, s.done_at from public.tasks s
                            where s.source_activity_id = a.id and s.cancelled_at is null
                            order by s.created_at, s.id limit 1) t on true
       order by a.created_at desc, a.id desc;
  else
    return query
      select a.id, a.type, a.outcome, left(a.body, 2000), char_length(a.body) > 2000, a.contact_id,
             nullif(btrim(k.first_name || ' ' || k.last_name), ''), a.user_id, p.first_name, p.last_name,
             a.created_at, a.edited_at, a.user_id = caller,
             case when a.user_id = caller and a.created_at > now() - interval '120 seconds'
                       and exists (select 1 from private.activity_undo u where u.activity_id = a.id)
                  then a.created_at + interval '120 seconds' end,
             t.title, t.due_date, t.due_at, t.done_at
        from (select x.* from public.activities x
               where x.company_id = p_company and (p_types is null or x.type = any (p_types))
                 and (x.created_at, x.id) < (p_before_at, p_before_id)
               order by x.created_at desc, x.id desc
               limit p_limit) a
        left join public.contacts k on k.id = a.contact_id
        left join public.profiles p on p.id = a.user_id
        left join lateral (select s.title, s.due_date, s.due_at, s.done_at from public.tasks s
                            where s.source_activity_id = a.id and s.cancelled_at is null
                            order by s.created_at, s.id limit 1) t on true
       order by a.created_at desc, a.id desc;
  end if;
end;
$$;

