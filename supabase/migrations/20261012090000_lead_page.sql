-- A span key's two ends, eastern zone first; null for a plain zone.
create function private.span_zones(p_key text) returns text[]
language plpgsql immutable parallel safe set search_path = '' as $$
begin
  return case p_key
    when 'AU' then array['Australia/Sydney', 'Australia/Perth']
    when 'BR' then array['America/Sao_Paulo', 'America/Manaus']
