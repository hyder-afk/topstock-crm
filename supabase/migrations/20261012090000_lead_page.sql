-- The lead guard (INVOKER, BEFORE INSERT OR UPDATE; its name sorts after enforce_org_and_owner). Rules:
--  1. a country change clears a picked zone, unless the same statement picks a new one (checked by rule 2);
--  2. a zone set or changed must be one of the country's choices (constant message: the value never reaches a log);
--  3. a next call date set or changed is at most 2 years ahead (people only: maintenance sessions are left alone);
--     unchanged dates are never checked, so overdue leads stay editable;
--  4. a phone change clears the wrong-number mark; otherwise a mark goes from empty to the server's time, can be
--     cleared, and any other change keeps the first time (the client never chooses it);
--  5. a lead entering Cool off with no next call date, or one that is not in the future, comes back in 90 days (an old
--     retry date would otherwise bring it back at once). Imports, the edit form and direct writes included.
create function private.lead_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and new.country is distinct from old.country
     and not (new.timezone is not null and new.timezone is distinct from old.timezone) then
    new.timezone := null;
  end if;
  if new.timezone is not null and (tg_op = 'INSERT' or new.timezone is distinct from old.timezone)
     and not private.zone_fits_country(new.timezone, new.country) then
    raise exception 'this time zone is not one of the zones of the lead''s country'
      using errcode = '22023', hint = 'zone_not_in_country';
  end if;
  if (select auth.uid()) is not null and new.next_action_at is not null
     and (tg_op = 'INSERT' or new.next_action_at is distinct from old.next_action_at)
     and new.next_action_at > now() + interval '2 years' then
    raise exception 'the next call date is too far ahead' using errcode = '22023', hint = 'bounds';
  end if;
  if tg_op = 'UPDATE' then
    if new.phone is distinct from old.phone then
      new.phone_wrong_at := null;
    elsif old.phone_wrong_at is null and new.phone_wrong_at is not null then
      new.phone_wrong_at := now();
    elsif new.phone_wrong_at is not null then
      new.phone_wrong_at := old.phone_wrong_at;
    end if;
  end if;
  if new.lead_status = 'cool_off' and (tg_op = 'INSERT' or old.lead_status is distinct from 'cool_off')
     and (new.next_action_at is null or new.next_action_at <= now()) then
    new.next_action_at := now() + interval '90 days';
  end if;
  return new;
end;
$$;
create trigger lead_guard before insert or update on public.companies
  for each row execute function private.lead_guard();

-- The contact guard: rule 4 for a contact's number (contacts are never imported, and a client cannot insert a mark).
create function private.contact_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.phone is distinct from old.phone then
    new.phone_wrong_at := null;
  elsif old.phone_wrong_at is null and new.phone_wrong_at is not null then
    new.phone_wrong_at := now();
  elsif new.phone_wrong_at is not null then
    new.phone_wrong_at := old.phone_wrong_at;
  end if;
  return new;
end;
$$;
create trigger contact_guard before update on public.contacts
  for each row execute function private.contact_guard();

-- Audit: as Day 4a, plus next_action_at and phone_wrong_at join the columns an update diff leaves out (the entry that
-- moved them is the record). The time zone stays audited.
create or replace function private.audit_row() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  hidden constant text[] := array['search_text', 'email_key', 'phone_key', 'name_key'];
  is_activity constant boolean := tg_table_name = 'activities';
  rec jsonb := (case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end) - hidden;
  diff jsonb;
begin
  if is_activity and tg_op = 'INSERT' then
    return new;
  end if;
  if tg_op = 'UPDATE' then
    select jsonb_object_agg(n.key, jsonb_build_object('old', o.value, 'new', n.value))
      into diff
      from jsonb_each(to_jsonb(new)) n
      join jsonb_each(to_jsonb(old)) o using (key)
     where n.value is distinct from o.value
       and n.key not in ('updated_at', 'last_activity_at', 'next_action_at', 'phone_wrong_at')
       and not n.key = any (hidden)
       and not (is_activity and n.key = 'body');
    if is_activity and (to_jsonb(new) -> 'body') is distinct from (to_jsonb(old) -> 'body') then
      diff := coalesce(diff, '{}'::jsonb) || jsonb_build_object('body', jsonb_build_object(
                'changed', true, 'old_len', char_length(to_jsonb(old) ->> 'body'),
                'new_len', char_length(to_jsonb(new) ->> 'body')));
    end if;
    if diff is null then
      return new;
    end if;
  elsif tg_op = 'INSERT' and tg_table_name = 'companies' and rec ->> 'import_batch_id' is not null then
    diff := jsonb_build_object('import_batch_id', rec -> 'import_batch_id');
  elsif tg_op = 'INSERT' then
    diff := jsonb_build_object('new', rec);
  elsif tg_table_name = 'companies' and rec ->> 'import_batch_id' is not null
        and rec ->> 'updated_at' = rec ->> 'created_at'
        and exists (select 1 from public.import_batches b
                    where b.id = (rec ->> 'import_batch_id')::uuid and b.status = 'rolling_back') then
    diff := jsonb_build_object('import_batch_id', rec -> 'import_batch_id', 'undo', true);
  elsif is_activity then
    diff := jsonb_build_object('old', (rec - 'body') || jsonb_build_object('body_len', char_length(rec ->> 'body')));
  else
    diff := jsonb_build_object('old', rec);
  end if;
  insert into public.audit_log (org_id, actor_id, action, table_name, record_id, diff_json)
  values ((rec ->> 'org_id')::uuid, (select auth.uid()), lower(tg_op), tg_table_name, rec ->> 'id', diff);
  return coalesce(new, old);
end;
$$;

-- ===========================================================================
-- Part 3. Undo records and the delete rules that go with them
-- ===========================================================================
-- What log_activity changed, so undo_activity can put it back. Private schema: no API endpoint. Not audited (no lead
-- text, short-lived). prev_status is null when the author could not change the lead (nothing to put back there).
create table private.activity_undo (
  activity_id uuid primary key references public.activities (id) on delete cascade,
  org_id uuid not null references public.orgs (id),
  user_id uuid not null,
  prev_status text,
  new_status text,
  prev_next_action_at timestamptz,
  new_next_action_at timestamptz,
  prev_owner_id uuid,
  new_owner_id uuid,
  owner_changed boolean not null default false,
  wrong_company boolean not null default false,
  wrong_contact_id uuid,
  created_task_id uuid,
  completed_task_ids uuid[] not null default '{}' check (cardinality(completed_task_ids) <= 20),
  cancelled_task_ids uuid[] not null default '{}' check (cardinality(cancelled_task_ids) <= 50),
  created_at timestamptz not null default now()
);
alter table private.activity_undo enable row level security;
create policy require_mfa on private.activity_undo as restrictive to authenticated
  using ((select private.has_aal2())) with check ((select private.has_aal2()));
-- Own rows only, with no time bound (the clean-up in log_activity must see the old ones; undo_activity checks the
-- 2-minute window itself).
create policy undo_own on private.activity_undo for all to authenticated
  using (user_id = (select auth.uid()) and org_id = (select private.current_org_id()))
  with check (user_id = (select auth.uid()) and org_id = (select private.current_org_id()));
revoke all on private.activity_undo from public, anon, authenticated;
grant select, insert, delete on private.activity_undo to authenticated;  -- no update: a record is used once

-- Deleting an entry: a fresh code (author, manager or admin), or, without a code, the author's own entry from the last
-- 2 minutes that has no undo record. undo_activity consumes the record first, so an outcome logged through
-- log_activity can only be removed through undo_activity, which puts the lead back; an entry inserted directly
-- changed no lead.
drop policy activities_delete on public.activities;
create policy activities_delete on public.activities for delete to authenticated using (
  org_id = (select private.current_org_id()) and (
       ((select private.has_recent_aal2(600)) and ((select private.is_manager_or_admin()) or user_id = (select auth.uid())))
    or (user_id = (select auth.uid()) and created_at > now() - interval '120 seconds'
        and not exists (select 1 from private.activity_undo u where u.activity_id = activities.id))));

-- Deleting a task: a fresh code as in 4a, or, without a code, a task the caller made from their own entry of the last
-- 2 minutes whose undo record is already consumed (undo_activity), and that nobody has touched since (open, never
-- updated).
drop policy tasks_delete on public.tasks;
create policy tasks_delete on public.tasks for delete to authenticated using (
  org_id = (select private.current_org_id()) and (
       ((select private.has_recent_aal2(600))
        and (assignee_id = (select auth.uid()) or created_by = (select auth.uid()) or (select private.is_manager_or_admin())))
    or (created_by = (select auth.uid()) and updated_at = created_at and done_at is null and cancelled_at is null
        and exists (select 1 from public.activities a
                     where a.id = tasks.source_activity_id and a.user_id = (select auth.uid())
                       and a.created_at > now() - interval '120 seconds')
        and not exists (select 1 from private.activity_undo u where u.activity_id = tasks.source_activity_id))));

