-- 09:00 local time on the Nth weekday (Monday to Friday) after p_at, in the key's zone (a span uses its eastern end).
-- DST-safe: the local date plus 09:00 is turned back into an instant in that zone.
create function private.next_working_day(p_at timestamptz, p_days integer, p_key text) returns timestamptz
language plpgsql stable set search_path = '' as $$
declare
  z constant text := coalesce((private.span_zones(p_key))[1], p_key);
  d date;
  n integer := 0;
begin
  if z is null or p_at is null or p_days is null or p_days not between 1 and 10 then
    raise exception 'a zone, a time and 1 to 10 working days are needed' using errcode = '22023', hint = 'bounds';
  end if;
  d := (p_at at time zone z)::date;
  while n < p_days loop
    d := d + 1;
    if extract(isodow from d) < 6 then
      n := n + 1;
    end if;
  end loop;
  return (d + time '09:00') at time zone z;
end;
$$;

-- Calls in a row without reaching anyone (no answer or voicemail), among the lead's 6 latest calls: one short read on
-- the timeline index.
create function private.call_attempts(p_company uuid) returns integer
language sql stable set search_path = '' as $$
  with last6 as (
    select x.outcome, row_number() over (order by x.created_at desc, x.id desc) as rn
      from (select a.outcome, a.created_at, a.id from public.activities a
             where a.company_id = p_company and a.type = 'call'
             order by a.created_at desc, a.id desc
             limit 6) x)
  select coalesce(min(rn) filter (where outcome not in ('no_answer', 'voicemail')) - 1, count(*))::integer from last6
$$;

-- The signed-in person's zone for "today" (profiles.timezone, checked against the database in 4c; until then a value
-- PostgreSQL does not know falls back to Europe/Paris instead of failing).
create function private.caller_zone() returns text
language plpgsql stable set search_path = '' as $$
declare
  z text := (select p.timezone from public.profiles p where p.id = (select auth.uid()));
begin
  if z is null or z = '' then
    return 'Europe/Paris';
  end if;
  begin
    perform now() at time zone z;
  exception when invalid_parameter_value then
    return 'Europe/Paris';
  end;
  return z;
end;
$$;

-- What log_activity answers, built from the entry and its undo record (the same answer for a replay).
create function private.logged_activity(p_id uuid, p_replayed boolean) returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'activity_id', a.id,
    'replayed', p_replayed,
    'editable', case when u.activity_id is not null then u.prev_status is not null end,
    'status_before', u.prev_status,
    'status_after', u.new_status,
    'next_action_at', u.new_next_action_at,
    'owner_changed', coalesce(u.owner_changed, false),
    'wrong_number_marked', coalesce(u.wrong_company or u.wrong_contact_id is not null, false),
    'task_id', u.created_task_id,
    'completed_task_ids', coalesce(to_jsonb(u.completed_task_ids), '[]'::jsonb),
    'cancelled_task_ids', coalesce(to_jsonb(u.cancelled_task_ids), '[]'::jsonb),
    'created_at', a.created_at,
    'undo_until', case when u.activity_id is not null then a.created_at + interval '120 seconds' end)
  from public.activities a
  left join private.activity_undo u on u.activity_id = a.id
  where a.id = p_id
$$;

