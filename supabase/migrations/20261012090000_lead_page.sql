-- Whether a zone may be picked for a lead in this country (only countries with several zones have choices).
create function private.zone_fits_country(p_zone text, p_country text) returns boolean
language plpgsql immutable parallel safe set search_path = '' as $$
begin
  return coalesce(p_zone = any (private.country_zone_choices(p_country)), false);
end;
$$;

-- The zone a lead is called on: its picked zone, else its country's zone or span key, else Europe/Paris (no country).
create function private.lead_call_zone(p_zone text, p_country text) returns text
language plpgsql immutable parallel safe set search_path = '' as $$
begin
  return coalesce(p_zone, private.country_call_zone(p_country), 'Europe/Paris');
end;
$$;

