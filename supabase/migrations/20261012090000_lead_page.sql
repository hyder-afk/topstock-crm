-- Day 4b: the lead page (design docs/evidence/day4/design.md sections 3.2, 4.1, 5.1 to 5.3, 5.5 and 6). What changes, in
-- plain words:
--  - every lead has a calling zone: its country's zone, or for a country with several zones the whole country's hours
--    (a "span", US 12:00 to 18:00 New York) until someone picks the lead's zone from a closed list; changing the country
--    resets a picked zone;
--  - a lead has a next call date, and the dialled number can be marked wrong (on the lead or a contact); the mark goes
--    away by itself when the number changes; the server sets its time;
--  - a lead entering Cool off without a future date comes back in 90 days;
--  - log_activity writes a call, email, WhatsApp message, meeting or note and, for a call, applies the outcome rules
--    (status, next call, follow-up task, owner of an unassigned lead) for people who may change the lead; anyone in the
--    team may log on any lead;
--  - undo_activity takes an entry back within 2 minutes and puts the lead back, field by field, only where nobody
--    changed it since; the undo record lives in the private schema (no API endpoint);
--  - the lead page reads one lead (get_lead, extended), its timeline (list_lead_activities, keyset) and its tasks;
--  - the status menu's "Until when?" for Cool off (bulk_update_leads gains p_next_action_at).
-- House rules (design section 3): every function sets search_path = ''; every RPC is SECURITY INVOKER with static SQL
-- (row level security decides every row; no format(), no EXECUTE); the guards are INVOKER triggers; every CHECK that
-- user input can reach has a pre-check with a constant message first; clients get column grants only.
-- Error hints added here (SQLSTATE 22023 unless noted): zone_not_in_country, bounds, outcome, body_required, dialled,
-- follow_up_required, follow_up_range, task_title, undo_expired, bad_cursor, bad_types, until_cool_off_only; 42501
-- not_editable and step_up; P0002 for a lead, contact, entry or task that is missing or not visible.

